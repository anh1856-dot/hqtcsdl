'use strict';
const assert=require('node:assert/strict');
const a=require('./js/mock-api');
let passed=0;
function check(desc,method,path,body,token,expected){const [status,result]=a.route(method,path,body||{},token); assert.equal(status,expected,desc+': '+JSON.stringify(result));passed++; return result;}
const login=check('login','POST','/api/auth/login',{email:'an.le@example.test',password:'123456'},null,200);
const token=login.data.token;
check('wrong password','POST','/api/auth/login',{email:'an.le@example.test',password:'wrong'},null,401);
check('unauthorized','GET','/api/my/trays',{},null,401);
check('health','GET','/api/health',{},null,200);
check('css independent packages','GET','/api/packages',{},null,200);
for(const path of ['/api/auth/me','/api/my/trays','/api/my/trays/11','/api/my/transactions','/api/my/harvests','/api/environment','/api/environment/1/history?hours=24&groupBy=hour','/api/trays/available','/api/rentals','/api/notifications','/api/notifications/preferences'])check(path,'GET',path,{},token,200);
check('missing tray','GET','/api/my/trays/9999',{},token,404);
check('missing room','GET','/api/environment/999/history',{},token,404);
check('invalid time range','GET','/api/environment/1/history?hours=9999',{},token,400);
const order={packageId:1,trayCount:2,roomId:1,mushroomTypeId:1,paymentMethod:'EWallet'};
for(const n of [-1,0,1.5,6,NaN,'2',null])check('invalid quantity '+n,'POST','/api/rentals',{...order,trayCount:n},token,400);
check('invalid room','POST','/api/rentals',{...order,roomId:999},token,400);
check('invalid type','POST','/api/rentals',{...order,mushroomTypeId:999},token,400);
check('invalid payment','POST','/api/rentals',{...order,paymentMethod:'Hack'},token,400);
check('good rental','POST','/api/rentals',order,token,201);
check('second rental','POST','/api/rentals',{...order,trayCount:1},token,201);
check('fake tray link','POST','/api/rentals/link',{trayCode:'FAKE-123'},token,404);
check('real tray link','POST','/api/rentals/link',{trayCode:'tray-r01-013'},token,200);
check('duplicate tray link','POST','/api/rentals/link',{trayCode:'tray-r01-013'},token,409);
check('scheduled harvest rejected','POST','/api/deliveries',{harvestId:3,requestType:'Pickup'},token,409);
check('invalid delivery type','POST','/api/deliveries',{harvestId:1,requestType:'Spaceship'},token,400);
check('invalid delivery phone','POST','/api/deliveries',{harvestId:1,requestType:'Delivery',address:'abc',receiverPhone:'abc'},token,400);
const d=check('create delivery','POST','/api/deliveries',{harvestId:1,requestType:'Delivery',address:'123 street',receiverPhone:'0901234567'},token,201);
check('duplicate delivery','POST','/api/deliveries',{harvestId:1,requestType:'Pickup'},token,409);
check('cancel delivery','PATCH','/api/deliveries/'+d.data.RequestId+'/cancel',{},token,200);
check('cancel again','PATCH','/api/deliveries/'+d.data.RequestId+'/cancel',{},token,409);
check('wrong current password','PUT','/api/auth/me/password',{currentPassword:'wrong',newPassword:'newpass'},token,400);
check('too short password','PUT','/api/auth/me/password',{currentPassword:'123456',newPassword:'a'},token,400);
check('update password','PUT','/api/auth/me/password',{currentPassword:'123456',newPassword:'newpass'},token,200);
check('old pwd invalid','POST','/api/auth/login',{email:'an.le@example.test',password:'123456'},null,401);
check('new pwd valid','POST','/api/auth/login',{email:'an.le@example.test',password:'newpass'},null,200);
check('register invalid','POST','/api/auth/register',{email:'wrong',fullName:'A',password:'123456'},null,400);
const reg=check('register','POST','/api/auth/register',{email:'new@example.test',fullName:'New Customer',password:'abcdef'},null,201);
check('duplicate account','POST','/api/auth/register',{email:'new@example.test',fullName:'New Customer',password:'abcdef'},null,409);
const tok2=reg.data.token;
assert.equal(check('new account trays','GET','/api/my/trays',{},tok2,200).data.length,0);
assert.equal(check('new account payments','GET','/api/my/transactions',{},tok2,200).data.length,0);
check('cross account tray','GET','/api/my/trays/11',{},tok2,404);
check('cross account harvest','POST','/api/deliveries',{harvestId:1,requestType:'Pickup'},tok2,404);
check('new account login','POST','/api/auth/login',{email:'new@example.test',password:'abcdef'},null,200);
check('valid profile','PUT','/api/auth/me',{fullName:'Updated',phone:'0901112223',address:'HCMC'},tok2,200);
check('invalid profile','PUT','/api/auth/me',{fullName:'',phone:'012'},tok2,400);
check('read notification','PATCH','/api/notifications/2/read',{},token,200);
check('mark all','PATCH','/api/notifications/read-all',{},token,200);
check('prefs invalid','PUT','/api/notifications/preferences',{type:'Unknown',isEnabled:true},token,400);
check('prefs valid','PUT','/api/notifications/preferences',{type:'Alert',isEnabled:false},token,200);
check('delete notification','DELETE','/api/notifications/1',{},token,200);
check('delete missing','DELETE','/api/notifications/10000',{},token,404);
console.log('PASS '+passed+' mock API tests');
